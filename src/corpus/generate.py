"""Build the legal-safe synthetic corpus release.

The generator writes only inert, generated bytes. It never downloads or executes
third-party tools or recovered content.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import struct
import zipfile
from pathlib import Path

SCHEMA = "dfir-corpus-manifest/v1"
VERSION = "1.0.0"
GENERATOR = "synthetic-corpus"

GROUPS = {
    "disk": ["ntfs-normal", "ext4-normal", "fat32-normal", "gpt-mbr", "empty", "malformed-partition", "truncated", "encrypted-wrapper", "fragmented", "deleted", "slack", "zero-byte", "duplicate", "offset-variation", "cfp-style", "e01-optional"],
    "memory": ["win-normal", "linux-normal", "empty", "truncated", "bad-page-map", "fragmented", "encrypted-wrapper", "high-entropy"],
    "uac": ["normal", "denied", "empty", "malformed-evtx", "fragmented-records", "encrypted-wrapper", "duplicates", "clock-skew"],
    "velociraptor": ["normal", "empty", "malformed-json", "malformed-csv", "missing-columns", "duplicates", "partial-zip", "encrypted-zip", "fragmented-parts", "schema-v2"],
    "artifacts": ["browser-chromium", "browser-firefox", "browser-malformed", "plaso-jsonl", "hayabusa-sigma-csv", "yara-string-hash", "malformed-oversized"],
}


def canonical(value: object) -> bytes:
    return (json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":")) + "\n").encode()


def digest(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            h.update(block)
    return h.hexdigest()


def _disk_bytes(name: str) -> bytes:
    data = bytearray(2 * 1024 * 1024)
    if name == "ext4-normal":
        entry = bytearray(16); entry[4] = 0x83; struct.pack_into("<II", entry, 8, 1, 1024)
        data[446:462] = entry; data[510:512] = b"\x55\xaa"; data[512 + 0x38:512 + 0x3a] = b"\x53\xef"
    elif name == "gpt-mbr":
        data[510:512] = b"\x55\xaa"; data[512:520] = b"EFI PART"
    elif name == "malformed-partition":
        data[510:512] = b"\x00\x00"
    else:
        marker = f"synthetic-disk:{name}\n".encode(); data[:len(marker)] = marker
    return bytes(data)


def _zip_bytes(kind: str) -> bytes:
    import io
    out = io.BytesIO()
    with zipfile.ZipFile(out, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        for name, value in (("metadata.json", {"fixture": kind, "synthetic": True}), ("results.jsonl", {"record": "generated", "source": "example.test"})):
            info = zipfile.ZipInfo(name, date_time=(1980, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            archive.writestr(info, canonical(value))
    return out.getvalue()


def fixture_bytes(group: str, scenario: str) -> tuple[str, bytes]:
    if group == "disk": return ("dd", _disk_bytes(scenario))
    if group in {"uac", "velociraptor"}: return ("zip", _zip_bytes(f"{group}:{scenario}"))
    if group == "memory":
        prefix = b"\x7fELF" if scenario == "linux-normal" else b"DUMP" if scenario.startswith("win") else b"VMCORE\x00"
        return ("dmp", prefix + f":synthetic-memory:{scenario}:profile-v1\n".encode())
    if scenario == "malformed-oversized": return ("json", b'{"path":"../escape","value":"' + b"A" * 1024 + b'"}\n')
    return ("jsonl", canonical({"fixture": f"{group}:{scenario}", "url": "https://example.test/generated", "synthetic": True}))


def build(release: str, seed: int, root: Path) -> Path:
    if release != "corpus-v1": raise ValueError("only corpus-v1 is currently supported")
    root = root.resolve(); root.mkdir(parents=True, exist_ok=True)
    records: list[dict] = []
    for group, scenarios in GROUPS.items():
        for scenario in scenarios:
            fixture_id = f"{group}-{scenario}-001"
            extension, content = fixture_bytes(group, scenario)
            rel = Path("fixtures") / group / f"{fixture_id}.{extension}"
            path = root / rel; path.parent.mkdir(parents=True, exist_ok=True); path.write_bytes(content)
            expected_rel = Path("expected") / group / f"{fixture_id}.json"
            negative = "malformed" in scenario or scenario in {"truncated", "bad-page-map"}
            stopped = "encrypted" in scenario
            expected = {"schema": "dfir-golden/v1", "fixture_id": fixture_id, "status": "key_required" if stopped else "invalid_input" if negative else "complete", "scenario": scenario, "synthetic": True, "observations": [], "unresolved": []}
            expected_path = root / expected_rel; expected_path.parent.mkdir(parents=True, exist_ok=True); expected_path.write_bytes(canonical(expected))
            records.append({"schema": SCHEMA, "corpus_version": VERSION, "fixture_id": fixture_id, "group_id": f"{group}-{scenario}", "class": group, "scenario": ["normal" if scenario.endswith("normal") else scenario], "relative_path": rel.as_posix(), "format": f"synthetic-{extension}", "size_bytes": len(content), "sha256": digest(path), "generator": {"name": GENERATOR, "version": VERSION, "seed": seed}, "source": {"kind": "generated", "license": "CC0-1.0"}, "expected_answer": expected_rel.as_posix(), "metadata_policy": "synthetic-only"})
    manifest = root / "manifest.jsonl"; manifest.write_bytes(b"".join(canonical(r) for r in records))
    (root / "manifest.sha256").write_text(digest(manifest) + "  manifest.jsonl\n")
    (root / "build-metadata.json").write_bytes(canonical({"release": release, "corpus_version": VERSION, "generator": GENERATOR, "generator_version": VERSION, "seed": seed, "fixture_count": len(records), "source_policy": "synthetic-only; no network retrieval"}))
    (root / "NOTICE.md").write_text("# Corpus notice\n\nAll bytes in this release are generated locally, inert, and dedicated to CC0-1.0. No public reference evidence is included.\n")
    (root / "README.md").write_text("# corpus-v1\n\nGenerated with `python -m corpus.generate --release corpus-v1 --seed 41001 --out build/corpus-v1`. Verify with `python -m corpus.verify --root build/corpus-v1`.\n")
    return root


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--release", default="corpus-v1")
    parser.add_argument("--seed", type=int, default=41001)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args(); build(args.release, args.seed, args.out)
    print(args.out.resolve())

if __name__ == "__main__": main()
